export function shuffle<T>(items: readonly T[], pickIndex: (upperBound: number) => number): T[] {
  const order = [...items]
  for (let i = order.length - 1; i > 0; i--) {
    const j = pickIndex(i + 1)
    const item = order[i]
    order[i] = order[j]
    order[j] = item
  }
  return order
}
